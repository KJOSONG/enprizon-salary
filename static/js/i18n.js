/* ════════════════════════════════════════════════
   i18n 引擎
   ════════════════════════════════════════════════ */

function getLang() {
  return localStorage.getItem('kilwa_lang') || 'zh';
}

function setLang(lang) {
  localStorage.setItem('kilwa_lang', lang);
}

/* 翻译函数 */
function t(key) {
  const lang = getLang();
  const dict = I18N_DICT[lang] || I18N_DICT['zh'];
  return dict[key] !== undefined ? dict[key] : key;
}

